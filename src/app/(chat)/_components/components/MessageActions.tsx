'use client'

import type React from 'react'
import { Copy, Check, RotateCcw, GitFork, Volume2, VolumeX, Loader2 } from 'lucide-react'
import { useSpeechStatus } from '@/hooks/useSpeechSynthesis'
import { prewarmSpeech } from '@/lib/tts/controller'
import { ModelDropdown } from '@/components/ui/model-dropdown'
import { getModelDisplayName, getVendorColor, ModelInfo } from '@/lib/models'
import { Tooltip, TooltipContent, TooltipTrigger } from '@/components/ui/tooltip'
import { buttonVariants } from '@/components/ui/button'
import { cn } from '@/lib/utils'
import { useQuery } from 'convex/react'
import { api } from '../../../../../convex/_generated/api'

interface MessageActionsProps {
  messageId: string
  content: string
  modelId?: string
  copiedId: string | null
  retryDropdownId: string | null
  speakingMessageId: string | null
  selectedModel: ModelInfo
  isStreaming: boolean
  onCopy: (text: string, messageId: string) => void
  onReadAloud: (text: string, messageId: string) => void
  onRetryClick: (messageId: string) => void
  onRetryWithModel: (messageId: string, modelId: string) => void
  onCloseRetryDropdown: () => void
  onBranch: (messageId: string) => void
  isSignedIn: boolean
  /** Extra classes for the button group (e.g. reveal-on-hover); the model label stays visible. */
  buttonsClassName?: string
  /** Trailing metadata such as the message time. */
  meta?: React.ReactNode
}

export function MessageActions({
  messageId,
  content,
  modelId,
  copiedId,
  retryDropdownId,
  speakingMessageId,
  selectedModel,
  isStreaming,
  onCopy,
  onReadAloud,
  onRetryClick,
  onRetryWithModel,
  onCloseRetryDropdown,
  onBranch,
  isSignedIn,
  buttonsClassName,
  meta,
}: MessageActionsProps) {
  const apiKeys = useQuery(api.api_keys.getApiKeys, isSignedIn ? {} : 'skip') || []
  const speechStatus = useSpeechStatus()
  return (
    <div className="relative flex h-7 items-center gap-2">
      {/* Model and time come first so the hover-revealed buttons never leave a gap before them */}
      {modelId && (
        <Tooltip>
          <TooltipTrigger asChild>
            <div className="flex cursor-help items-center gap-1.5 text-xs text-muted-foreground/80">
              <div className={cn('size-1.5 rounded-full', getVendorColor(modelId))} />
              <span>{getModelDisplayName(modelId)}</span>
            </div>
          </TooltipTrigger>
          <TooltipContent>Generated by {getModelDisplayName(modelId)}</TooltipContent>
        </Tooltip>
      )}
      {meta}
      {!isStreaming && (
        <div className={cn('flex items-center first:-ml-1.5', buttonsClassName)}>
          <Tooltip>
            <TooltipTrigger asChild>
              <button
                onClick={() => onCopy(content, messageId)}
                aria-label={copiedId === messageId ? 'Copied' : 'Copy message'}
                className={cn(buttonVariants({ variant: 'ghost', size: 'icon-xs' }), 'cursor-pointer')}
              >
                {copiedId === messageId ? <Check /> : <Copy />}
              </button>
            </TooltipTrigger>
            <TooltipContent>{copiedId === messageId ? 'Copied!' : 'Copy message'}</TooltipContent>
          </Tooltip>

          <Tooltip>
            <TooltipTrigger asChild>
              <button
                onClick={() => onReadAloud(content, messageId)}
                onPointerEnter={prewarmSpeech}
                onFocus={prewarmSpeech}
                aria-label={speakingMessageId === messageId ? 'Stop reading' : 'Read aloud'}
                className={cn(buttonVariants({ variant: 'ghost', size: 'icon-xs' }), 'cursor-pointer')}
              >
                {speakingMessageId === messageId ? (
                  speechStatus === 'loading' ? (
                    <Loader2 className="animate-spin" />
                  ) : (
                    <VolumeX />
                  )
                ) : (
                  <Volume2 />
                )}
              </button>
            </TooltipTrigger>
            <TooltipContent>{speakingMessageId === messageId ? 'Stop reading' : 'Read aloud'}</TooltipContent>
          </Tooltip>

          <Tooltip>
            <TooltipTrigger asChild>
              <button
                onClick={() => onBranch(messageId)}
                aria-label="Branch from this message"
                className={cn(buttonVariants({ variant: 'ghost', size: 'icon-xs' }), 'cursor-pointer')}
              >
                <GitFork />
              </button>
            </TooltipTrigger>
            <TooltipContent>Branch from this message</TooltipContent>
          </Tooltip>

          <Tooltip>
            <TooltipTrigger asChild>
              <button
                onClick={() => onRetryClick(messageId)}
                aria-label="Retry with model selection"
                className={cn(buttonVariants({ variant: 'ghost', size: 'icon-xs' }), 'cursor-pointer')}
              >
                <RotateCcw />
              </button>
            </TooltipTrigger>
            <TooltipContent>Retry with model selection</TooltipContent>
          </Tooltip>
        </div>
      )}

      {/* Anchored to the whole row (the message's left edge), not the retry button: the
          button sits after the model label, time and other actions, so on narrow screens a
          button-anchored menu would start far right and run off-screen. */}
      {!isStreaming && retryDropdownId === messageId && (
        <ModelDropdown
          selectedModel={selectedModel}
          onModelSelect={(modelId) => onRetryWithModel(messageId, modelId)}
          onClose={onCloseRetryDropdown}
          className="absolute inset-x-0 top-0 h-full"
          isSignedIn={isSignedIn}
          apiKeys={apiKeys}
        />
      )}
    </div>
  )
}
